// react-icons ships each pack as one huge file (react-icons/pi is ~1.3 MB). Production tree-shakes it, but dev mode loads and parses all of it.
// This script copies only the icons the app actually imports into lib/icons/<pack>.ts and points those imports at the subset.
// Re-run after adding a new icon from these packs:  node scripts/build-icon-subsets.mjs
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { join } from "node:path";

const PACKS = ["pi", "fa", "fa6"];
const SRC_DIRS = ["app", "components", "contexts", "lib", "store"];
const SKIP_DIR = new Set(["node_modules", ".next", "icons"]);

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIR.has(name)) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (/\.(tsx?|jsx?)$/.test(name)) out.push(full);
  }
  return out;
}

const files = SRC_DIRS.flatMap((d) => walk(d));
const used = Object.fromEntries(PACKS.map((p) => [p, new Set()]));
const importRe = (pack) => new RegExp(`import\\s*\\{([^}]*)\\}\\s*from\\s*["'](?:react-icons/${pack}|@/lib/icons/${pack})["']`, "g");

for (const file of files) {
  const text = readFileSync(file, "utf8");
  for (const pack of PACKS) {
    for (const m of text.matchAll(importRe(pack))) {
      for (const part of m[1].split(",")) {
        const name = part.trim().split(/\s+as\s+/)[0].trim();
        if (name) used[pack].add(name);
      }
    }
  }
}

mkdirSync("lib/icons", { recursive: true });
for (const pack of PACKS) {
  const source = readFileSync(`node_modules/react-icons/${pack}/index.mjs`, "utf8");
  const blocks = new Map();
  for (const m of source.matchAll(/export function (\w+) \(props\) \{\n  return (GenIcon\(.*\))\(props\);\n\};?/g)) {
    blocks.set(m[1], m[2]);
  }
  const names = [...used[pack]].sort();
  const missing = names.filter((n) => !blocks.has(n));
  if (missing.length) throw new Error(`react-icons/${pack} has no icon(s): ${missing.join(", ")}`);
  const body = names
    .map((n) => `export function ${n}(props: IconBaseProps) {\n  return ${blocks.get(n)}(props);\n}\n`)
    .join("\n");
  writeFileSync(
    `lib/icons/${pack}.ts`,
    `// AUTO-GENERATED by scripts/build-icon-subsets.mjs — do not edit.\nimport { GenIcon, type IconBaseProps } from "react-icons/lib";\n\n${body}`,
  );
  console.log(`${pack}: ${names.length} icons`);
}

let rewritten = 0;
for (const file of files) {
  let text = readFileSync(file, "utf8");
  let next = text;
  for (const pack of PACKS) {
    next = next.replace(
      new RegExp(`(import\\s*\\{[^}]*\\}\\s*from\\s*["'])react-icons/${pack}(["'])`, "g"),
      `$1@/lib/icons/${pack}$2`,
    );
  }
  if (next !== text) {
    writeFileSync(file, next);
    rewritten++;
  }
}
console.log(`rewrote imports in ${rewritten} files`);
